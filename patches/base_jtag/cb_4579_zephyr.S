.include "../macros.S" #; provides macros like MAKEPATCH and defines like SPR_HRMOR
.set CB_ORIG_SIZE, 0x00007f20
.set FixAddr3dest, 0x00005B08
	.globl _start
_start:

#;============================================================================
#; patch bl size                                                              
#;============================================================================
	MAKEPATCH 0x0000000c
0:
	.long (CB_ORIG_SIZE+UTILSIZE)
9:

#;============================================================================
#; patch entry point for dot output on uart                                   
#;============================================================================
	MAKEPATCH 0x000003c0
0:
	bl		UartDot - ((.-0b)+PatchAddr)
9:

#;============================================================================
#; fix reloc address                                                          
#;============================================================================
	MAKEPATCH 0x0000050c
0:
	li		%r25, 0
9:

#;============================================================================
#; fix reloc address                                                          
#;============================================================================
	MAKEPATCH 0x00000614
0:
	li		%r4, 0
9:

#;============================================================================
#; fix reloc address                                                          
#;============================================================================
	MAKEPATCH 0x00000720
0:
	li		%r26, 0
9:

#;============================================================================
#; fix CD flash address                                                       
#;============================================================================
	MAKEPATCH 0x00000764
0:
	b	FixCdAddr - ((.-0b)+PatchAddr)
9:

#;============================================================================
#; fix reloc address                                                          
#;============================================================================
	MAKEPATCH 0x000050bc
0:
	li		%r3, 0
9:

#;============================================================================
#; fix reloc address                                                          
#;============================================================================
	MAKEPATCH 0x000050e8
0:
	li		%r3, 0
9:

#;============================================================================
#; fix reloc address                                                          
#;============================================================================
	MAKEPATCH 0x00005118
0:
	li		%r4, 0
9:

#;============================================================================
#; copy patches/patch CD                                                      
#;============================================================================
	MAKEPATCH 0x00005140
0:
	b	CopyPatches - ((.-0b)+PatchAddr)
9:

#;============================================================================
#; fix fuse address/range                                                     
#;============================================================================
	MAKEPATCH 0x000052ec
0:
	bl	FixFuseAddr1 - ((.-0b)+PatchAddr)
9:
#;——————————————————————————————————————————————————————————
	MAKEPATCH 0x00005300
0:
	addi	%r11, %r11, 1
9:
#;——————————————————————————————————————————————————————————
	MAKEPATCH 0x00005308
0:
	cmpwi	cr6, %r11, 0xC
9:

#;============================================================================
#; remove smc size restriction        cmplwi    cr6, r29, 0x3000              
#;============================================================================
	MAKEPATCH 0x00005600
0:
	nop
	nop
	nop
9:

#;============================================================================
#; fix fuse address/range                                                     
#;============================================================================
	MAKEPATCH 0x000056e8
0:
	bl	FixFuseAddr1 - ((.-0b)+PatchAddr)
9:
#;——————————————————————————————————————————————————————————
	MAKEPATCH 0x00005700
0:
	addi	%r11, %r11, 1
	cmplwi	cr6, %r11, 0xC
9:

#;============================================================================
#; disable hardware init script                                               
#;============================================================================
	MAKEPATCH 0x00005918
0:
	nop
9:

#;============================================================================
#; fix fuse address/range                                                     
#;============================================================================
	MAKEPATCH 0x00005ca8
0:
	bl	FixFuseAddr2 - ((.-0b)+PatchAddr)
9:
#;——————————————————————————————————————————————————————————
	MAKEPATCH 0x00005cb8
0:
	addi	%r11, %r11, 1
	cmplwi	cr6, %r11, 0xC
9:

#;============================================================================
#; disable HmacSha                                                            
#;============================================================================
	MAKEPATCH 0x00005d18
0:
	nop
9:

#;============================================================================
#; utility functions                                                          
#;============================================================================
	MAKEPATCH CB_ORIG_SIZE
	.set UartDot, PatchAddr
	.set FixFuseAddr1, (PatchAddr + (1f - 0f))
	.set FixFuseAddr2, (PatchAddr + (2f - 0f))
	.set FixCdAddr, (PatchAddr + (3f - 0f))
	.set CopyPatches, (PatchAddr + (4f - 0f))
	.set UTILSIZE, (9f - 0f)
#;——————————————————————————————————————————————————————————
0: #; UartDot                                               
#;——————————————————————————————————————————————————————————
	li		%r3, 0x2E #; '.'
	lis		%r4, 0x8000
	ori		%r4, %r4, 0x200
	rldicr	%r4, %r4, 32,31
	oris	%r4, %r4, 0xEA00 		#; 0x80000200_EA000000
	slwi	%r3, %r3, 24
	stw		%r3, 0x1014(%r4)		#; 0x80000200_EA001014
waitloop:
	lwz		%r3, 0x1018(%r4) 		#; 0x80000200_EA001018
	rlwinm.	%r3, %r3, 0,6,6
	beq		waitloop
	lis		%r3, 0x100					#; orig inst replaced to get here
	blr
#;——————————————————————————————————————————————————————————
1: #; FixFuseAddr1                                          
#;——————————————————————————————————————————————————————————
	addis	%r31, %r11, 2
	addi	%r31, %r31, -0x6500 # 0x9B00
	blr
#;——————————————————————————————————————————————————————————
2: #; FixFuseAddr2                                          
#;——————————————————————————————————————————————————————————
	addis	%r9, %r10, 2
	addi	%r9, %r9, -0x6500 # 0x9B00
	blr
#;——————————————————————————————————————————————————————————
3: #; FixCdAddr                                             
#;——————————————————————————————————————————————————————————
	li		%r24, CB_ORIG_SIZE@l
	stw		%r24, 0(%r8)
	b		FixAddr3dest - ((.-0b)+PatchAddr)
#;——————————————————————————————————————————————————————————
4: #; CopyPatches                                           
#;——————————————————————————————————————————————————————————
	lis		%r3, 0x8000
	sldi	%r3, %r3, 32
	oris	%r3, %r3, 0x100
	ori		%r3, %r3, 0x1000
	lis		%r4, 0x8000
	sldi	%r4, %r4, 32
	oris	%r4, %r4, 0x400
	addi	%r3, %r3, -4
	addi	%r4, %r4, -4

copyPatchIter:
	lwzu	%r5, 4(%r3)
	cmpwi	%r5, -1
	beq		return
	add		%r5, %r4, %r5
	lwzu	%r6, 4(%r3)
	mtctr	%r6

copyPatchLoop:
	lwzu	%r6, 4(%r3)
	stwu	%r6, 4(%r5)
	bdnz	copyPatchLoop
	b		copyPatchIter

return:
	blr
	.long 0
	.long 0
	.long 0
9:

#;============================================================================
	.long 0xFFFFFFFF
	.end
