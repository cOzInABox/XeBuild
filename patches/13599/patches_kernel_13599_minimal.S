	.globl _start
_start:

#;============================================================================
#;   Send Dot Character            li      %r3, 0x200                         
#;============================================================================
	MAKEPATCH 0x00001880
	.set PrintDotDone, (PatchAddr + (9f - 0f))
0:
	ba      PrintDot                #; patches
9:

#;============================================================================
#;   Change Thread Hold Address      addis   %r4, %r3, -3                     
#;============================================================================
	MAKEPATCH 0x00000C60
	.set FixHoldAddrDone, (PatchAddr + (9f - 0f))
0:
	ba      FixHoldAddr
9:

#;============================================================================
#;   Setup Fuse Row Pointer to point at Virtual Fuses                         
#;   Change Increment and Range Check of Fuse Row Pointer                     
#;============================================================================
	MAKEPATCH 0x00001E64
0:
	bla     FixFusesAddr
9:
#;--------------------------------------
	MAKEPATCH 0x00001E7C  #; addi    %r11, %r11, 0x40
0:
	addi	%r11, %r11, 1
	cmplwi	cr6, %r11, 0xC
9:
#;——————————————————————————————————————————————————————————
	MAKEPATCH 0x00008A80
0:
	bla     FixFusesAddr
9:
#;--------------------------------------
	MAKEPATCH 0x00008AB0  #; addi    %r11, %r11, 0x40
0:
	addi    %r11, %r11, 0x0001
	cmplwi  cr6, %r11, 0x000c
9:
#;——————————————————————————————————————————————————————————
	MAKEPATCH 0x00008BEC
0:
	bla     FixFusesAddr
9:
#;--------------------------------------
	MAKEPATCH 0x00008C20  #; addi    %r11, %r11, 0x40
0:
	addi    %r11, %r11, 0x0001
	cmplwi  cr6, %r11, 0x000c
9:
#;——————————————————————————————————————————————————————————
	MAKEPATCH 0x00008D0C
0:
	bla     FixFusesAddr
9:
#;--------------------------------------
	MAKEPATCH 0x00008D40  #; addi    %r11, %r11, 0x40
0:
	addi    %r11, %r11, 0x0001
	cmplwi  cr6, %r11, 0x000c
9:
#;——————————————————————————————————————————————————————————
	MAKEPATCH 0x00008F7C
0:
	bla     FixFusesAddr
9:
#;--------------------------------------
	MAKEPATCH 0x00008FB0   #; addi    %r11, %r11, 0x40
0:
	addi    %r11, %r11, 0x0001
	cmplwi  cr6, %r11, 0x000c
9:
#;——————————————————————————————————————————————————————————
	MAKEPATCH 0x000090CC
0:
	bla     FixFusesAddr
9:
#;--------------------------------------
	MAKEPATCH 0x00009100  #; addi    %r11, %r11, 0x40
0:
	addi    %r11, %r11, 0x0001
	cmplwi  cr6, %r11, 0x000c
9:
#;——————————————————————————————————————————————————————————
	MAKEPATCH 0x0000918C
0:
	bla     FixFusesAddr
9:
#;--------------------------------------
	MAKEPATCH 0x000091BC  #; addi    %r11, %r11, 0x40
0:
	addi    %r11, %r11, 0x0001
	rldicr  %r9, %r9, 3,60		#; no change here
	cmpwi   cr6, %r11, 0x000c
9:
#;——————————————————————————————————————————————————————————
	MAKEPATCH 0x0000942C
0:
	bla     FixFusesAddr
9:
#;--------------------------------------
	MAKEPATCH 0x0000945C  #; addi    %r11, %r11, 0x40
0:
	addi    %r11, %r11, 0x0001
	rldicr  %r9, %r9, 3,60		#; no change here
	cmpwi   cr6, %r11, 0x000c
9:


#;============================================================================
#;   Utility Functions                                                        
#;============================================================================
	MAKEPATCH 0x0000A474
	.set PrintDot, PatchAddr
	.set FixFusesAddr, (PatchAddr + (1f - 0f))
	.set FixHoldAddr, (PatchAddr + (2f - 0f))
	.set PrintChar, (PatchAddr + (3f - 0f))

#;——————————————————————————————————————————————————————————
#; PrintDot                                                 
#;——————————————————————————————————————————————————————————
0:
.ifdef __NOKV_HASH
	lhz     %r3, BldrFlags(0)
	li		%r4, 0x20
	andc	%r3, %r3, %r4
	sth     %r3, BldrFlags(0)
.endif
	li      %r3, 'M'
	bla     PrintChar

	li      %r3, '\n'
	bla     PrintChar

	li      %r3, 0x0200
	ba      PrintDotDone

#;——————————————————————————————————————————————————————————
#; FixFusesAddr                                             
#;——————————————————————————————————————————————————————————
1:
	lis     %r3, 0x0002
	addi    %r3, %r3, -0x6500
	blr

#;——————————————————————————————————————————————————————————
#; FixHoldAddr                                              
#;——————————————————————————————————————————————————————————
2:
	lis     %r4, 0x8000
	rldicr  %r4, %r4, 32, 31
	oris    %r4, %r4, 0x100
	ori     %r4, %r4, 0x3080 	#; 0x80000000_01003080 - had to patch freeboot.bin
	ba      FixHoldAddrDone

#;——————————————————————————————————————————————————————————
#; PrintChar                                                
#;——————————————————————————————————————————————————————————
3:
	lis     %r4, 0x8000
	ori     %r4, %r4, 0x0200
	rldicr  %r4, %r4, 32, 31
	oris    %r4, %r4, 0xea00
	slwi    %r3, %r3, 24
	stw     %r3, 0x1014(%r4)
4:
	lwz     %r3, 0x1018(%r4)
	rlwinm. %r3, %r3, 0, 6, 6
	beq     4b
	blr
9:


